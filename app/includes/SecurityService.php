<?php

declare(strict_types=1);

namespace AESBin;

use AltchaOrg\Altcha\Algorithm\Pbkdf2;
use AltchaOrg\Altcha\Altcha;
use AltchaOrg\Altcha\CreateChallengeOptions;
use AltchaOrg\Altcha\Payload;
use AltchaOrg\Altcha\VerifySolutionOptions;
use PDO;
use RuntimeException;
use Throwable;

defined("AESBIN_APP") || exit;

/**
 * app/includes/SecurityService.php — AESBin login protection
 *
 *   - Honeypot field validation (ignored by password managers)
 *   - Rate limiting: counts failures per client in the rate_limit table,
 *     kept separate from activity_log, which the owner may cap or empty.
 *     See RATE_LIMIT_BUCKETS in helpers.php.
 *   - Captcha verification: self-hosted ALTCHA proof of work
 *
 * Config keys read here (defaults in config_template.php: SETTINGS_DEFAULTS,
 * CAPTCHA_LEVEL_DEFAULT):
 *   security.login_max_attempts, security.login_window
 *   captcha.enabled       off when the key is missing
 *   captcha.show_footer   "Protected by ALTCHA" credit link, on by default
 *   captcha.show_logo     small ALTCHA logo inside the widget, on by default
 *   captcha.level         'low' | 'medium' | 'high'
 *   captcha.hmac_secret, captcha.key_signature_secret
 *                         generated by the installer; both required, at least
 *                         CAPTCHA_SECRET_MIN_LENGTH characters and different
 *                         (captcha_keys_valid())
 */

/**
 * Thrown by SecurityService::checkRateLimit() when a client is over the
 * failure threshold; carries the seconds until retry.
 *
 * Callers catch THIS class, never RuntimeException: PDOException extends
 * RuntimeException, and a broader catch would send SQLSTATE text (table
 * prefix, database name) to an unauthenticated caller as a 429.
 */
final class RateLimitException extends RuntimeException
{
    public function __construct(string $message, public readonly int $retryAfter)
    {
        parent::__construct($message);
    }
}

class SecurityService
{
    private PDO $db;
    private array $cfg;

    public function __construct(PDO $db, array $config = [])
    {
        $this->db = $db;
        $this->cfg = $config;
    }

    // ── Honeypot ──────────────────────────────────────────────────────────────

    /**
     * Honeypot field name, derived from the (non-secret) table prefix so it
     * differs per install. Password managers ignore it: nothing about the
     * name looks like a real field.
     */
    public function honeypotName(): string
    {
        $seed = defined("DB_PREFIX") ? DB_PREFIX : "aesbin";
        return "field_" . substr(hash("sha256", $seed . "_hp"), 0, 8);
    }

    /**
     * Answer a filled honeypot (likely a bot) like the form's own failure,
     * after a delay that looks like real authentication work, and count it as
     * $event with reason "honeypot", so it gets the same lockout.
     *
     * Callers enforce their rate limit first: the usleep() would otherwise
     * let a filled honeypot tie up a PHP worker for ~1 s per request, uncapped.
     *
     * @param array $error The form's usual failure payload, answered with 403
     * @param array $meta  Extra log fields besides the reason
     */
    public function enforceHoneypot(array $body, string $event, array $error, array $meta = []): void
    {
        $name = $this->honeypotName();
        if (!isset($body[$name]) || $body[$name] === "") {
            return;
        }
        log_activity($this->db, $event, null, null, ["reason" => "honeypot"] + $meta);
        usleep(random_int(800000, 1500000));
        json_response($error, 403);
    }

    /**
     * The captcha step of a public form, when the captcha is operational
     * (see captchaOperational()). A bad token never reaches the form's own
     * failure counter, so it is counted in $bucket, which is also checked
     * first.
     *
     * @param "login.captcha_fail"|"recovery.captcha_fail" $bucket
     */
    public function enforceCaptcha(array $body, string $bucket): void
    {
        if (!$this->captchaOperational()) {
            return;
        }
        $this->enforceRateLimit($bucket);
        if (!$this->verifyCaptcha($body["captcha_token"] ?? null)) {
            log_activity($this->db, $bucket);
            json_response(["error" => __("captcha_error")], 403);
        }
    }

    // ── Rate limit ────────────────────────────────────────────────────────────

    /**
     * Throw RateLimitException if the current client (see
     * rate_limit_subject()) is over the failure threshold.
     *
     * Lockout recovery: security.login_max_attempts => 0 in config.php
     * disables the per-client limits (the global TOTP limit stays); otherwise
     * the block clears after login_window.
     *
     * @param int|null $maxOverride  Threshold instead of the configured one,
     *        for buckets whose failures are not credential guesses (e.g.
     *        share.token_probe: usually a visitor reloading a dead link).
     *        Ignored when rate limiting is off.
     */
    public function checkRateLimit(
        string $event = "login.failure",
        ?int $maxOverride = null
    ): void {
        $remaining = $this->rateLimitStatus($event, $maxOverride);
        if ($remaining !== null) {
            $mins = (int) ceil($remaining / 60);
            // Callers send getMessage() to the client, so it is translated.
            throw new RateLimitException(
                __($mins === 1 ? "rate_limit_blocked_one" : "rate_limit_blocked", [
                    "minutes" => $mins,
                ]),
                $remaining
            );
        }
    }

    /**
     * checkRateLimit() for an action handler: a block is answered here with a
     * 429 and retry_after, which the front end shows as a countdown.
     */
    public function enforceRateLimit(
        string $event = "login.failure",
        ?int $maxOverride = null
    ): void {
        try {
            $this->checkRateLimit($event, $maxOverride);
        } catch (RateLimitException $e) {
            json_response(
                ["error" => $e->getMessage(), "retry_after" => $e->retryAfter],
                429
            );
        }
    }

    /**
     * enforceRateLimit() for a check that records its failure only after slow
     * work (Argon2id, a TOTP step): without a lock, parallel requests would all
     * pass the check before any of them counts, and a burst would get far more
     * guesses than the limit allows. Serialises one subject's attempts on
     * $bucket (rate_limit_subject(), so "*" for a global bucket), then checks
     * again. The lock is held until the request ends; a request that cannot
     * take it within db_advisory_lock()'s timeout gets a 503.
     */
    public function serializeAttempts(string $bucket): void
    {
        try {
            db_advisory_lock(
                $this->db,
                "attempt:" . $bucket . ":" . rate_limit_subject($bucket),
                "Attempt check busy."
            );
        } catch (RuntimeException) {
            json_response(["error" => __("err_attempt_busy")], 503);
        }
        $this->enforceRateLimit($bucket);
    }

    /**
     * Side-effect-free form of checkRateLimit(), safe on every page load.
     * Null when not blocked, otherwise seconds remaining.
     *
     * Sliding window: the block ends when enough failures have aged out of
     * login_window to bring the count below the threshold. Blocked requests
     * record nothing, so that moment does not move while blocked.
     */
    public function rateLimitStatus(
        string $event = "login.failure",
        ?int $maxOverride = null
    ): ?int {
        // Defaults come from SETTINGS_DEFAULTS in config_template.php.
        $max = setting_int($this->cfg, "login_max_attempts");
        $window = setting_int($this->cfg, "login_window");

        // A global bucket counts every client together, so its threshold is
        // never below RATE_LIMIT_GLOBAL_MAX, and 0 does not switch it off: it
        // caps guesses at a second factor spread over many addresses (see
        // RATE_LIMIT_GLOBAL_BUCKETS).
        if (in_array($event, RATE_LIMIT_GLOBAL_BUCKETS, true)) {
            $max = max($max, RATE_LIMIT_GLOBAL_MAX);
        } elseif ($max <= 0) {
            // 0 disables every per-client bucket (the self-lockout escape
            // hatch). Checked before the override, so it covers them all.
            return null;
        } elseif ($maxOverride !== null && $maxOverride > 0) {
            $max = $maxOverride;
        }
        $ip = rate_limit_subject($event);
        $since = gmdate("Y-m-d H:i:s", time() - $window);

        // From rate_limit, never activity_log (see the file header). A
        // successful ownership proof clears the relevant buckets: see
        // RATE_LIMIT_CLEARED_BY in helpers.php.
        $stmt = $this->db->prepare(
            "SELECT COUNT(*) FROM " . DB_PREFIX . "rate_limit
              WHERE bucket = :evt AND ip = :ip AND created_at > :since"
        );
        $stmt->execute([":evt" => $event, ":ip" => $ip, ":since" => $since]);
        $count = (int) $stmt->fetchColumn();

        if ($count < $max) {
            return null;
        }

        // Rows oldest first: the count drops below $max once row
        // ($count - $max) leaves the window.
        $stmt = $this->db->prepare(
            "SELECT created_at FROM " . DB_PREFIX . "rate_limit
              WHERE bucket = :evt AND ip = :ip AND created_at > :since
              ORDER BY created_at ASC
              LIMIT 1 OFFSET :offset"
        );
        $stmt->bindValue(":evt", $event);
        $stmt->bindValue(":ip", $ip);
        $stmt->bindValue(":since", $since);
        $stmt->bindValue(":offset", $count - $max, PDO::PARAM_INT);
        $stmt->execute();
        $first = $stmt->fetchColumn();
        $triggeredAt = strtotime(($first ?: "now") . " UTC");
        return max(1, $triggeredAt + $window - time());
    }

    // ── ALTCHA ────────────────────────────────────────────────────────────────

    /** @return bool True when ALTCHA is enabled in config. */
    public function captchaEnabled(): bool
    {
        return !empty($this->cfg["captcha"]["enabled"]);
    }

    /**
     * Whether the widget shows its "Protected by ALTCHA" link. Defaults to
     * true, unlike captchaEnabled(): this is attribution, not a control.
     */
    public function captchaShowFooter(): bool
    {
        return (bool) ($this->cfg["captcha"]["show_footer"] ?? true);
    }

    /** Whether the widget shows the ALTCHA logo. Defaults to true, as above. */
    public function captchaShowLogo(): bool
    {
        return (bool) ($this->cfg["captcha"]["show_logo"] ?? true);
    }

    /**
     * Proof-of-work level for new challenges (CAPTCHA_LEVELS in
     * config_template.php). Verification never depends on it.
     */
    public function captchaLevel(): string
    {
        return captcha_level((array) ($this->cfg["captcha"] ?? []));
    }

    /**
     * A fresh ALTCHA V2 challenge at $level, as the widget consumes it. V2 runs
     * a KDF in the proof of work; the counter range comes from the level and
     * must be set, or the puzzle would be a single zero byte.
     *
     * @param string      $hmacSecret Signs the challenge
     * @param string|null $keySecret  Enables the fast verification path; null
     *                                for a challenge nothing will verify
     */
    public static function createCaptchaChallenge(
        string $level,
        string $hmacSecret,
        ?string $keySecret = null
    ): array {
        require_once AESBIN_APP_DIR . "/includes/AltchaAutoload.php";
        register_altcha_autoloader();

        [$counterMin, $counterMax] = CAPTCHA_LEVELS[$level];
        $altcha = new Altcha(
            hmacSignatureSecret: $hmacSecret,
            hmacKeySignatureSecret: $keySecret
        );
        return $altcha->createChallenge(
            new CreateChallengeOptions(
                algorithm: new Pbkdf2(),
                cost: CAPTCHA_PBKDF2_COST,
                counter: random_int($counterMin, $counterMax),
                expiresAt: time() + CAPTCHA_EXPIRES
            )
        )->toArray();
    }

    /**
     * Verify an ALTCHA solution with the vendored library
     * (app/vendor/altcha-lib-php), which checks signature, proof of work and
     * expiry, then burn the challenge. The payload is the widget's
     * base64-encoded JSON ({challenge, solution}).
     *
     * @param mixed $payload  base64 JSON from the widget's hidden input, taken
     *                       from the request body as is: anything but a
     *                       non-empty string fails the captcha, not the request
     */
    private function verifyCaptcha(mixed $payload): bool
    {
        // Off, or enabled but not operational: pass, as documented at
        // captchaOperational().
        if (!$this->captchaOperational()) {
            return true;
        }
        if (!is_string($payload) || $payload === "") {
            return false;
        }

        require_once AESBIN_APP_DIR . "/includes/AltchaAutoload.php";
        register_altcha_autoloader();

        // verifySolution() checks the signed expiry and the challenge HMAC, so
        // tampered parameters fail here. The client submits the counter it
        // found, so verification costs one derivation however hard the
        // challenge was.
        try {
            $altcha = new Altcha(
                hmacSignatureSecret: $this->captchaSecret(),
                // Fast HMAC-only path; see captchaKeySecret().
                hmacKeySignatureSecret: $this->captchaKeySecret()
            );
            $result = $altcha->verifySolution(
                new VerifySolutionOptions(
                    payload: $payload,
                    algorithm: new Pbkdf2()
                )
            );
        } catch (Throwable) {
            // The library throws on a malformed payload: a failed captcha,
            // not a 500.
            return false;
        }
        if (!$result->verified) {
            return false;
        }

        // verifySolution() is stateless: without burning the challenge, one
        // solved payload could be replayed until it expires (10 minutes).
        return $this->consumeCaptchaChallenge($payload);
    }

    /**
     * Record an accepted ALTCHA challenge so it cannot be presented twice.
     * Returns false if it was already consumed. The PRIMARY KEY on
     * challenge_hash makes this race-free: of two concurrent replays, exactly
     * one INSERT succeeds.
     */
    private function consumeCaptchaChallenge(string $payload): bool
    {
        try {
            $parsed = Payload::fromBase64($payload);
        } catch (Throwable) {
            return false;
        }
        $params = $parsed->challenge->parameters;

        // The nonce (16 random bytes per challenge) is inside the signed
        // parameters verifySolution() has already checked, so it cannot be
        // swapped to dodge the burn.
        if ($params->nonce === "") {
            return false;
        }
        $hash = hash("sha256", $params->nonce);

        // Fallback so a row is never kept forever.
        $expires = $params->expiresAt ?? time() + CAPTCHA_EXPIRES;

        // Opportunistic cleanup, no scheduled task needed.
        $this->db->exec(
            "DELETE FROM " . DB_PREFIX . "captcha_used WHERE expires_at < NOW()"
        );
        $stmt = $this->db->prepare(
            "INSERT IGNORE INTO " . DB_PREFIX . "captcha_used
                (challenge_hash, expires_at) VALUES (:h, :e)"
        );
        $stmt->execute([
            ":h" => $hash,
            ":e" => gmdate("Y-m-d H:i:s", $expires),
        ]);
        // 0 rows: already consumed, a replay.
        return $stmt->rowCount() > 0;
    }

    /**
     * HMAC secret for ALTCHA's fast verification path: verifySolution()
     * checks one HMAC of the submitted key instead of re-running PBKDF2.
     *
     * No validity check of its own: every caller has already passed
     * captchaOperational(), which requires it to be valid and distinct from
     * hmac_secret.
     */
    public function captchaKeySecret(): string
    {
        return (string) ($this->cfg["captcha"]["key_signature_secret"] ?? "");
    }

    /**
     * HMAC secret backing every ALTCHA challenge signature.
     *
     * No fallback: a derivable default would be a public signing key, letting
     * anyone mint cheap challenges. config-sample.php ships hmac_secret => '',
     * so an empty, too-short or duplicate value is a real state and throws
     * (see captcha_keys_valid() in config_template.php).
     */
    public function captchaSecret(): string
    {
        $s = (string) ($this->cfg["captcha"]["hmac_secret"] ?? "");
        if (!$this->captchaOperational()) {
            throw new RuntimeException("captcha.hmac_secret is not configured");
        }
        return $s;
    }

    /**
     * True when ALTCHA is enabled AND both secrets are present, at least
     * CAPTCHA_SECRET_MIN_LENGTH characters and different from each other
     * (captcha_keys_valid() in config_template.php).
     *
     * Callers use this rather than captchaEnabled() so that missing or
     * invalid secrets do not lock the admin out: verifyCaptcha() passes, the
     * widget is hidden and the dashboard shows an amber notice instead.
     */
    public function captchaOperational(): bool
    {
        if (!$this->captchaEnabled()) {
            return false;
        }
        return captcha_keys_valid(
            $this->cfg["captcha"]["hmac_secret"] ?? null,
            $this->cfg["captcha"]["key_signature_secret"] ?? null
        );
    }
}
