#!/bin/sh
#
# bin/fetch-vendor.sh — download the third-party libraries at their latest
# published version, laid out the way AESBin expects.
#
#   ./bin/fetch-vendor.sh              # everything
#   ./bin/fetch-vendor.sh prism        # one library
#   ./bin/fetch-vendor.sh prism kjua   # some of them
#
# Requires curl (or wget) and tar (the two PHP libraries come as GitHub
# tarballs). Without zip, the staged files are left in place instead of
# archived. POSIX sh, so it also runs under Termux's dash/ash.
#
# ── IT INSTALLS NOTHING ──────────────────────────────────────────────────────
# The only output is bin/dist/aesbin-vendor-YYYYMMDD-HHMM.zip; the project's
# vendor folders are never touched. Updating a library means reading what
# changed and testing the feature it drives (docs/vendored-libraries.md names
# it), so the copy into the project stays a manual step.
#
# The archive holds public/vendor/<library>/ (what the browser loads) and
# app/vendor/<library>/ (PHP) at the same flat paths as the project, so it diffs
# cleanly against the project. Every file in it is upstream's, except the
# index.php stubs, generated by guard(). VERSIONS.txt at the archive root lists the versions
# downloaded, for app/includes/Vendor.php.
#
# ── WHY IT RESOLVES VERSIONS INSTEAD OF USING @latest ────────────────────────
# Minified builds carry no version marker, so a file fetched via @latest can
# never be identified afterwards. The version is resolved from the registry
# first, used explicitly in the URL and written to VERSIONS.txt.
#
# ── WHAT IT DOES NOT DOWNLOAD ────────────────────────────────────────────────
# altcha-lib-php: composer.json is skipped. The autoloader is our own
# app/includes/AltchaAutoload.php, standing in for Composer's.
#
# passkeys-php: only the tarball's src/ is taken, which leaves out _test/ (a
# manual browser harness) and composer.json. WebAuthn.php requires its own
# dependencies by relative path, so it needs no autoloader.
#
# Both PHP libraries are otherwise byte-identical to upstream.
#
# public/vendor/prism/ ships only prism.min.js. The styling
# (public/assets/css/prism-aesbin.css) is AESBin's own; see
# docs/vendored-libraries.md § Prism.
#
# public/vendor/pdfjs/nowasm/ is upstream code (Emscripten output from pdf.js's
# wasm/ directory). Only the folder name is ours: it holds the pure-JS
# fallbacks, never the .wasm files. See lib_pdfjs().

set -u

ROOT=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
HERE=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)

# Downloads are staged in a temporary directory, removed after a successful
# run. The archive goes to bin/dist/ (git-ignored), never the project root,
# which is what gets deployed. It is dated so successive pulls can be
# compared.
OUT=$(mktemp -d "${TMPDIR:-/tmp}/aesbin-vendor.XXXXXX")
mkdir -p "$HERE/dist"
ARCHIVE="$HERE/dist/aesbin-vendor-$(date '+%Y%m%d-%H%M').zip"
VERSIONS="$OUT/VERSIONS.txt"
# Every destination below is one flat level under a vendor folder: "$PVU" for
# the libraries the browser loads (public/vendor/, in the web root), "$AVU" for
# the PHP ones (app/vendor/, outside it).
AVU=app/vendor
PVU=public/vendor

KEEP_STAGING=0

# Removes the staging tree, unless no archive could be made to replace it.
cleanup() {
	if [ "$KEEP_STAGING" -eq 0 ]; then
		rm -rf "$OUT"
	else
		say "Staging kept at $OUT"
	fi
}

if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
	B=$(printf '\033[1m'); Y=$(printf '\033[33m'); R=$(printf '\033[0m')
else
	B=''; Y=''; R=''
fi

# Some POSIX shells lack `echo -e`; printf is portable.
say() { printf '%s\n' "$*"; }
die() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

# ── Downloader: curl if present, wget otherwise ──────────────────────────────
if command -v curl >/dev/null 2>&1; then
	fetch() { curl -fsSL "$1" -o "$2"; }
	fetch_stdout() { curl -fsSL "$1"; }
elif command -v wget >/dev/null 2>&1; then
	fetch() { wget -q -O "$2" "$1"; }
	fetch_stdout() { wget -q -O - "$1"; }
else
	die "curl or wget is required"
fi

FAILED=0

# get <url> <path-relative-to-staging>
get() {
	_dest="$OUT/$2"
	mkdir -p "$(dirname "$_dest")"
	if fetch "$1" "$_dest"; then
		# A zero-byte file is a failed download.
		if [ -s "$_dest" ]; then
			printf '    ok     %s\n' "$2"
		else
			rm -f "$_dest"
			printf '    EMPTY  %s\n' "$2"
			FAILED=1
		fi
	else
		printf '    FAILED %s\n' "$2"
		FAILED=1
	fi
}

# Pulls "field":"value" out of JSON without jq, which Termux often lacks.
# Enough for version and tag_name; not a JSON parser.
json_field() {
	sed -n 's/.*"'"$1"'"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -n 1
}

npm_latest() {
	fetch_stdout "https://registry.npmjs.org/$1/latest" | json_field version
}

# The PHP libraries are not on npm. The GitHub release API gives the exact tag,
# so the tarball URL needs no guess about a leading "v".
gh_latest_tag() {
	fetch_stdout "https://api.github.com/repos/$1/releases/latest" | json_field tag_name
}

# gh_subtree <owner/repo> <tag> <path-inside-tarball> <path-relative-to-staging>
#
# Takes a whole directory out of a release tarball. A hardcoded file list would
# silently miss any class upstream adds later.
gh_subtree() {
	if ! command -v tar >/dev/null 2>&1; then
		printf '    SKIP   %s (tar not installed)\n' "$4"
		FAILED=1
		return
	fi
	_tgz="$OUT/.tarball.tar.gz"
	_ex="$OUT/.tarball-extract"
	rm -rf "$_ex"; mkdir -p "$_ex"
	if ! fetch "https://codeload.github.com/$1/tar.gz/refs/tags/$2" "$_tgz"; then
		printf '    FAILED %s (tarball)\n' "$4"
		FAILED=1
		rm -rf "$_ex" "$_tgz"
		return
	fi
	# --strip-components=1 drops the "<repo>-<version>/" wrapper GitHub adds.
	if ! tar -xzf "$_tgz" -C "$_ex" --strip-components=1 2>/dev/null; then
		printf '    FAILED %s (extract)\n' "$4"
		FAILED=1
		rm -rf "$_ex" "$_tgz"
		return
	fi
	if [ ! -d "$_ex/$3" ]; then
		printf '    FAILED %s (%s not in the tarball)\n' "$4" "$3"
		FAILED=1
		rm -rf "$_ex" "$_tgz"
		return
	fi
	mkdir -p "$OUT/$4"
	cp -R "$_ex/$3/." "$OUT/$4/"
	printf '    ok     %s/ (from %s)\n' "$4" "$3"
	rm -rf "$_ex" "$_tgz"
}

# declared_version <role>: the version app/includes/Vendor.php declares for that
# role, or empty. Matched on 'role', the key the application itself uses.
declared_version() {
	awk -v want="$1" '
		/"version"[[:space:]]*=>/ {
			v = $0; sub(/.*=>[[:space:]]*"/, "", v); sub(/".*/, "", v)
		}
		/"role"[[:space:]]*=>/ {
			r = $0; sub(/.*=>[[:space:]]*"/, "", r); sub(/".*/, "", r)
			if (r == want) { print v; exit }
		}
	' "$ROOT/app/includes/Vendor.php" 2>/dev/null
}

# record <name> <downloaded-version> <role-in-Vendor.php>
#
# Writes the shipped version, plus the downloaded one only when it differs.
# A difference is marked with !!! at the start of the line: it survives
# redirection to a file, and the count below greps for it.
record() {
	_dec=$(declared_version "${3:-}")
	[ -n "$_dec" ] || _dec='?'
	if [ "$_dec" = "$2" ]; then
		printf '    %-24s %s\n' "$1" "$_dec" >> "$VERSIONS"
	else
		printf '!!! %-24s %s -> %s\n' "$1" "$_dec" "$2" >> "$VERSIONS"
	fi
}

# guard <path-relative-to-staging>: writes the index.php silence stub into
# that directory and every subdirectory (nowasm/, ...). Under public/vendor/
# a backstop for public/.htaccess's Options -Indexes on servers that ignore
# it; under app/vendor/, which has no URL, the same convention as every other
# folder of the project (bin/lint.sh 3h), in case the web root is set wrong.
guard() {
	find "$OUT/$1" -type d | while IFS= read -r d; do
		printf '<?php // Silence...\n' > "$d/index.php"
	done
}

# License file names vary between projects: try the usual ones and stop at
# the first that answers.
get_license() {
	# $1 = package base URL, $2 = destination directory
	for _name in LICENSE LICENSE.md LICENSE.txt license; do
		if fetch "$1/$_name" "$OUT/$2/LICENSE.txt" 2>/dev/null && [ -s "$OUT/$2/LICENSE.txt" ]; then
			printf '    ok     %s/LICENSE.txt\n' "$2"
			return 0
		fi
	done
	rm -f "$OUT/$2/LICENSE.txt"
	printf '    (no license file found automatically for %s)\n' "$2"
}

# ── Libraries ────────────────────────────────────────────────────────────────

lib_altcha() {
	say "${B}altcha${R} (widget)"
	v=$(npm_latest altcha)
	[ -n "$v" ] || { say "    could not resolve version"; FAILED=1; return; }
	say "    version $v"
	base="https://cdn.jsdelivr.net/npm/altcha@$v"
	# dist/main (workers and stylesheet inlined), UMD build: unlike the ES
	# module it can read its nonce from document.currentScript. See
	# docs/vendored-libraries.md § altcha (widget).
	get "$base/dist/main/altcha.umd.min.cjs" "$PVU/altcha/altcha.umd.min.cjs"
	get "$base/README.md" "$PVU/altcha/README.md"
	get_license "$base" "$PVU/altcha"
	guard $PVU/altcha
	record altcha "$v" altcha
}

lib_kjua() {
	say "${B}kjua${R}"
	v=$(npm_latest kjua)
	[ -n "$v" ] || { say "    could not resolve version"; FAILED=1; return; }
	say "    version $v"
	base="https://cdn.jsdelivr.net/npm/kjua@$v"
	get "$base/dist/kjua.min.js" "$PVU/kjua/kjua.min.js"
	get "$base/README.md" "$PVU/kjua/README.md"
	# kjua has no LICENSE file (the MIT text is in README.md), so write a
	# pointer instead of trying get_license().
	cat > "$OUT/$PVU/kjua/LICENSE.txt" <<-EOF
	kjua ships no separate LICENSE file. See the "License" section in
	README.md, in this same directory, for the full MIT text and copyright
	notice.
	EOF
	guard $PVU/kjua
	record kjua "$v" kjua
}

lib_pdfjs() {
	say "${B}pdf.js${R}"
	v=$(npm_latest pdfjs-dist)
	[ -n "$v" ] || { say "    could not resolve version"; FAILED=1; return; }
	say "    version $v"
	# Pinned into every URL so a release landing mid-run cannot mix builds
	# (see the apiVersion check below), and so the number recorded for
	# app/includes/Vendor.php is the one actually downloaded.
	base="https://cdn.jsdelivr.net/npm/pdfjs-dist@$v"
	# Minified builds exist only in the npm package. legacy/build/, not build/:
	# the modern build targets only the latest browser releases (it calls
	# Map.prototype.getOrInsertComputed, Math.sumPrecise, Promise.try, ...),
	# so PDF preview would fail on current Firefox ESR, Safari and
	# not-quite-latest Chromium. The rest of AESBin needs far less.
	#
	# Both files or neither: pdf.js refuses to start when the bundle's and the
	# worker's apiVersion differ.
	get "$base/legacy/build/pdf.min.mjs" "$PVU/pdfjs/pdf.min.mjs"
	get "$base/legacy/build/pdf.worker.min.mjs" "$PVU/pdfjs/pdf.worker.min.mjs"

	# Image decoders. preview.js sets useWasm:false (WebAssembly would need
	# 'wasm-unsafe-eval' in script-src for the whole page) and points wasmUrl
	# at vendor/pdfjs/nowasm/, so pdf.js loads these pure-JS fallbacks. They
	# must match the bundle version, like the worker.
	#
	# jbig2 also decodes CCITT Fax Group 4, used by most black-and-white scans;
	# without it those pages render blank. openjpeg handles JPEG 2000.
	get "$base/wasm/jbig2_nowasm_fallback.js" "$PVU/pdfjs/nowasm/jbig2_nowasm_fallback.js"
	get "$base/wasm/openjpeg_nowasm_fallback.js" "$PVU/pdfjs/nowasm/openjpeg_nowasm_fallback.js"

	# The decoders' licences, which must travel with the redistributed code.
	#
	# LICENSE_QCMS and LICENSE_PDFJS_QCMS are left out: qcms exists only as
	# .wasm, is never loaded with useWasm:false, and is not redistributed.
	# Add them if upstream ships a qcms JS fallback.
	get "$base/wasm/LICENSE_JBIG2" "$PVU/pdfjs/nowasm/LICENSE_JBIG2"
	get "$base/wasm/LICENSE_PDFJS_JBIG2" "$PVU/pdfjs/nowasm/LICENSE_PDFJS_JBIG2"
	get "$base/wasm/LICENSE_OPENJPEG" "$PVU/pdfjs/nowasm/LICENSE_OPENJPEG"
	get "$base/wasm/LICENSE_PDFJS_OPENJPEG" "$PVU/pdfjs/nowasm/LICENSE_PDFJS_OPENJPEG"

	get "$base/README.md" "$PVU/pdfjs/README.md"
	get_license "$base" "$PVU/pdfjs"

	# nowasm/README.md is AESBin's own. The full reasoning is in
	# docs/vendored-libraries.md § pdf.js.
	cat > "$OUT/$PVU/pdfjs/nowasm/README.md" <<-EOF
	# nowasm/: pdf.js's image decoders, JS build

	Two files, both genuinely upstream, taken from pdf.js's own wasm/
	directory: jbig2_nowasm_fallback.js (also decodes CCITT Fax Group 4 —
	the compression scanned documents use) and openjpeg_nowasm_fallback.js
	(JPEG 2000, rarer). "nowasm" is upstream's own naming for the plain-JS
	build of each decoder, as opposed to the WebAssembly one.

	AESBin uses these instead of the .wasm versions because
	WebAssembly.instantiate() needs 'wasm-unsafe-eval' in script-src for
	every script on the page, not just pdf.js — too wide a CSP hole for two
	image codecs. preview.js sets useWasm:false and points pdf.js at this
	directory instead.

	Regenerated by bin/fetch-vendor.sh pdfjs, alongside the main
	bundle. See docs/vendored-libraries.md § pdf.js for the rest.
	EOF
	guard $PVU/pdfjs
	record pdfjs-dist "$v" pdfjs
}

lib_passkeysphp() {
	say "${B}report-uri/passkeys-php${R} (server)"
	# Maintained fork of lbuchs/WebAuthn, chosen for an origin-validation fix
	# in _checkOrigin() that upstream never merged. See
	# docs/vendored-libraries.md § passkeys-php.
	tag=$(gh_latest_tag report-uri/passkeys-php)
	[ -n "$tag" ] || { say "    could not resolve tag"; FAILED=1; return; }
	say "    tag $tag"
	# The whole src/ tree, verbatim. The library accepts only attestation fmt
	# "none", so there is no format allowlist to configure.
	gh_subtree report-uri/passkeys-php "$tag" src "$AVU/passkeys-php/src"
	get "https://raw.githubusercontent.com/report-uri/passkeys-php/$tag/LICENSE" "$AVU/passkeys-php/LICENSE"
	get "https://raw.githubusercontent.com/report-uri/passkeys-php/$tag/README.md" "$AVU/passkeys-php/README.md"
	get "https://raw.githubusercontent.com/report-uri/passkeys-php/$tag/SECURITY.md" "$AVU/passkeys-php/SECURITY.md"
	# Attribution to Lukas Buchs, the original author; ships with LICENSE.
	get "https://raw.githubusercontent.com/report-uri/passkeys-php/$tag/NOTICE.md" "$AVU/passkeys-php/NOTICE.md"
	record passkeys-php "${tag#v}" webauthn
}

