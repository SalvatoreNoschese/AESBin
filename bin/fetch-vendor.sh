lib_prism() {
	say "${B}Prism${R} (assembled bundle)"
	v=$(npm_latest prismjs)
	[ -n "$v" ] || { say "    could not resolve version"; FAILED=1; return; }
	say "    version $v"
	base="https://cdn.jsdelivr.net/npm/prismjs@$v"

	# Prism has no single distributable: the bundle is core plus components,
	# concatenated up to yaml in components.json declaration order, which
	# satisfies every dependency (clike before javascript and php, css before scss, markup
	# before markdown and markup-templating, markup-templating before php).
	#
	# Keep this list in sync with docs/vendored-libraries.md § Prism (bin/lint.sh 3d).
	tmp="$OUT/.prism-tmp"
	rm -rf "$tmp"; mkdir -p "$tmp"

	PARTS="prism-core prism-markup prism-css prism-clike prism-javascript \
prism-apacheconf prism-bash prism-batch prism-diff prism-docker prism-ini \
prism-json prism-markdown prism-markup-templating prism-nginx prism-php \
prism-powershell prism-python prism-scss prism-sql prism-yaml \
prism-csv prism-log prism-toml \
prism-c prism-cpp prism-csharp prism-java prism-kotlin prism-go prism-rust \
prism-typescript prism-swift prism-ruby"
	# The components from csv on are appended at the end, each after what
	# it needs (clike, javascript, c before cpp). Before adding a component,
	# check its "require" in
	#   https://cdn.jsdelivr.net/npm/prismjs@VERSION/components.json
	# and place it after what it names.

	ok=1
	for part in $PARTS; do
		if fetch "$base/components/$part.min.js" "$tmp/$part.min.js" && [ -s "$tmp/$part.min.js" ]; then
			:
		else
			printf '    FAILED components/%s.min.js\n' "$part"
			ok=0
		fi
	done
	if fetch "$base/plugins/line-numbers/prism-line-numbers.min.js" "$tmp/zz-line-numbers.min.js" \
		&& [ -s "$tmp/zz-line-numbers.min.js" ]; then
		:
	else
		printf '    FAILED plugins/line-numbers/prism-line-numbers.min.js\n'
		ok=0
	fi

	if [ "$ok" -eq 1 ]; then
		mkdir -p "$OUT/$PVU/prism"
		: > "$OUT/$PVU/prism/prism.min.js"
		for part in $PARTS; do
			cat "$tmp/$part.min.js" >> "$OUT/$PVU/prism/prism.min.js"
			# Minified files do not always end with a newline or semicolon.
			printf '\n' >> "$OUT/$PVU/prism/prism.min.js"
		done
		cat "$tmp/zz-line-numbers.min.js" >> "$OUT/$PVU/prism/prism.min.js"
		printf '\n' >> "$OUT/$PVU/prism/prism.min.js"
		printf '    ok     %s/prism/prism.min.js (%s parts + line-numbers)\n' "$PVU" "$(printf '%s\n' $PARTS | wc -l | tr -d ' ')"
	else
		FAILED=1
	fi
	rm -rf "$tmp"

	get "$base/README.md" "$PVU/prism/README.md"
	get_license "$base" "$PVU/prism"
	guard $PVU/prism
	record prismjs "$v" prism
}

# ── Run ──────────────────────────────────────────────────────────────────────

ALL="altcha prism kjua pdfjs passkeys-php altcha-lib-php"

# HOW-TO-APPLY.txt promises a drop-in app/vendor/ only when no library was named.
if [ "$#" -gt 0 ]; then
	TARGETS="$*"
	IS_FULL_RUN=0
else
	TARGETS="$ALL"
	IS_FULL_RUN=1
fi

{
	printf 'Downloaded on %s\n' "$(date '+%Y-%m-%d %H:%M')"
	printf 'Lines marked !!! differ from app/includes/Vendor.php: shipped -> downloaded.\n\n'
} > "$VERSIONS"

say "${B}Downloading into${R} $OUT"
say ""

for t in $TARGETS; do
	case "$t" in
		altcha) lib_altcha ;;
		prism)  lib_prism ;;
		kjua)   lib_kjua ;;
		pdfjs)  lib_pdfjs ;;
		passkeys-php)     lib_passkeysphp ;;
		altcha-lib-php)   lib_altchaphp ;;
		*)      say "unknown library: $t (valid: $ALL)"; FAILED=1 ;;
	esac
	say ""
done

# app/vendor/index.php and public/vendor/index.php are generated by guard()
# like every other stub. app/vendor/ is created even when only browser
# libraries were fetched, so the archive always has both folders.
if [ -d "$OUT/$AVU" ] || [ -d "$OUT/$PVU" ]; then
	mkdir -p "$OUT/$AVU"
	guard $AVU
fi
if [ -d "$OUT/$PVU" ]; then
	guard $PVU
fi

say "${B}Versions${R}"
# Colour only lines that begin with !!!, not the header that mentions it.
while IFS= read -r _line; do
	case "$_line" in
		'!!! '*) say "    ${Y}${_line}${R}" ;;
		*)       say "    $_line" ;;
	esac
done < "$VERSIONS"
say ""

_diverged=$(grep -c '^!!! ' "$VERSIONS" 2>/dev/null || true)
[ -n "$_diverged" ] || _diverged=0
if [ "$_diverged" -gt 0 ]; then
	say "${Y}${_diverged} to carry over into both:${R}"
	say "${Y}  app/includes/Vendor.php · docs/vendored-libraries.md${R}"
	say ""
fi

if [ "$FAILED" -eq 0 ]; then
	# At the archive root, not inside app/vendor/, so it is seen before anyone
	# replaces the folder.
	if [ -d "$OUT/$AVU" ]; then
		if [ "$IS_FULL_RUN" -eq 1 ]; then
		cat > "$OUT/HOW-TO-APPLY.txt" <<-EOF
		A full run: every one of the six libraries is in here, in the
		same two folders as in the project: public/vendor/ for the
		ones the browser loads (altcha, kjua, pdfjs, prism), app/vendor/
		for the PHP ones (altcha-lib-php, passkeys-php). Plus an
		index.php in every folder under app/vendor/ and public/vendor/
		(generated fresh). Both are complete, byte-for-byte mirrors of the
		project's.

		To apply:
		  1. In your AESBin project, delete the whole app/vendor/ and
		     public/vendor/ folders.
		  2. Copy app/vendor/ and public/vendor/ from here in their place.

		docs/vendored-libraries.md in the project explains what's in each
		library and how to verify a specific one after updating.
		EOF
	else
		cat > "$OUT/HOW-TO-APPLY.txt" <<-EOF
		A partial run: only the library or libraries you named are
		in here, not all six. Do NOT replace a whole vendor folder
		with one from here: it would delete every library not named.

		To apply, for each library folder you see in here, under
		public/vendor/ (browser) or app/vendor/ (PHP):
		  1. In your AESBin project, delete that same folder.
		  2. Copy the folder from here in its place.

		The index.php files of app/vendor/ and public/vendor/ are in
		here too (generated fresh) so a diff against a full mirror
		doesn't flag them as missing; they need no copying back for a
		per-library update, but doing so is harmless.

		docs/vendored-libraries.md in the project explains what's in
		each library and how to verify a specific one after updating.
		EOF
	fi
	fi

	# Created only when everything succeeded: a partial zip looks complete.
	if command -v zip >/dev/null 2>&1; then
		# Zipped from INSIDE the staging directory, so app/ and public/
		# sit at the archive root at the same depth as in the project.
		if (cd "$OUT" && zip -qr "$ARCHIVE" .); then
			say "Archive ready: $ARCHIVE"
		else
			say "Could not write the archive to $ARCHIVE"
			FAILED=1
		fi
	else
		say "zip is not installed; the files are in $OUT (not removed)"
		KEEP_STAGING=1
	fi

	say ""
	say "${B}Done.${R} Before copying anything into app/vendor/:"
	say "  - read its section in docs/vendored-libraries.md"
	say "  - skim the release notes between your version and this one"
	say "  - update the version in app/includes/Vendor.php and in the table of"
	say "    docs/vendored-libraries.md (bin/lint.sh fails if they disagree)"
